"""S15 SRT renderer (AC-5 golden broadcast, AC-6 RLM and BOM).

The expected bytes are written out by hand below, not generated by the renderer. The golden
test compares every byte, so a wrong BOM, RLM or timestamp fails it.
Imports happen inside helpers so the module collects before the code exists.
"""

import importlib
from dataclasses import replace
from types import ModuleType
from typing import Any

from tests.unit.render.test_cues import _transcript

FIRST = [
    ("مرحبا", 0, 500),
    ("بيكم", 500, 900),
    ("في", 900, 1100),
    ("البرنامج.", 1100, 1800),
]
SECOND = [("أهلا", 2000, 2400), ("بيك", 2400, 2800), ("يا", 2800, 3000), ("أستاذ", 3000, 3500)]

GOLDEN = (
    "\ufeff"
    "1\n00:00:00,000 --> 00:00:01,800\n\u200fمرحبا بيكم في البرنامج.\u200f\n\n"
    "2\n00:00:02,000 --> 00:00:03,500\n\u200fأهلا بيك يا أستاذ\n\n"
)


def _mod(name: str) -> ModuleType:
    return importlib.import_module(name)


def two_speaker_transcript() -> Any:
    first = _transcript(FIRST, speaker="S1")
    second = _transcript(SECOND, speaker="S2")
    return replace(
        first,
        segments=first.segments + second.segments,
        speakers=first.speakers + second.speakers,
    )


def _render() -> bytes:
    cues_mod = _mod("transcribe_engine.domain.render.cues")
    srt = _mod("transcribe_engine.domain.render.srt")
    cues = cues_mod.build_cues(two_speaker_transcript(), cues_mod.SubtitleProfile())
    return srt.render_srt(cues)


def test_golden_broadcast() -> None:
    """AC-5: the broadcast SRT matches the hand-written golden bytes exactly."""
    assert _render() == GOLDEN.encode("utf-8")


def test_rlm_and_bom() -> None:
    """AC-6: the file starts with the UTF-8 BOM, and every text line starts with U+200F."""
    data = _render()
    assert data.startswith(b"\xef\xbb\xbf")
    lines = data.decode("utf-8-sig").split("\n")
    text_lines = [line for line in lines if line and not line[0].isdigit() and "-->" not in line]
    assert text_lines
    assert all(line.startswith("\u200f") for line in text_lines)
